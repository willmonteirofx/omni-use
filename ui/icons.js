function icon(name, size = 18) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[name]}</svg>`;
}

function setIcon(el, name) {
  el.innerHTML = icon(name, el.classList.contains("small") ? 15 : 18);
}

function applyIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => setIcon(el, el.dataset.icon));
}

function escapeHtml(s) {
  return String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
}

function formatBytes(n) {
  if (n == null) return "–";
  const gb = n / 1024 ** 3;
  return gb >= 1 ? `${gb.toFixed(1)} GB` : `${Math.round(n / 1024 ** 2)} MB`;
}

function formatTokens(n) {
  return n >= 1000 ? `${(n / 1000).toFixed(1).replace(".0", "")}k` : String(n || 0);
}

/** Minimal markdown for model answers: **bold**, `- `/`* ` lists, line breaks. */
function renderMarkdown(text) {
  const inline = (s) => escapeHtml(s).replace(/\*\*(.+?)\*\*/g, "<b>$1</b>").replace(/`(.+?)`/g, "<code>$1</code>");
  let html = "";
  let inList = false;
  for (const line of String(text ?? "").split("\n")) {
    const item = line.match(/^\s*[-*]\s+(.*)$/);
    if (item && !inList) html += "<ul>";
    if (!item && inList) html += "</ul>";
    inList = !!item;
    html += item ? `<li>${inline(item[1])}</li>` : line.trim() ? `<p>${inline(line)}</p>` : "";
  }
  return html + (inList ? "</ul>" : "");
}
